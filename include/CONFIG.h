/*******************************************************************************
 * 文件名称 : CONFIG.h
 * 描    述 : 全局配置汇总头文件。
 *
 *            两种使用方式，通过宏 CH572BLE_ROM 切换：
 *
 *            ① 静态库方式（默认）
 *               定义：无（或不定义 CH572BLE_ROM）
 *               链接：-lCH572BLE -lISP572
 *               特点：协议栈编进应用固件，应用单独一个 hex 就能跑。
 *
 *            ② ROM 镜像方式
 *               定义：CH572BLE_ROM=1
 *               链接：-lISP572（**不要**再链接 CH572BLE）
 *               特点：协议栈固化在 Flash 的固定地址段，应用只调用绝对地址。
 *                     应用固件体积大幅下降；升级时可只换应用固件。
 *                     需要先把 CH572BLE_ROM.hex 烧进芯片。
 ******************************************************************************/
#ifndef __CONFIG_H
#define __CONFIG_H

/*----------------------------------------------------------------------------
 * 1. 芯片标识
 *--------------------------------------------------------------------------*/
#define CHIP_ID                     ID_CH572

/*----------------------------------------------------------------------------
 * 2. 引入 BLE 固件库
 *
 *    与 WCH 官方 CH59xBLE_ROM 的做法一致：
 *      - 静态库方式：包含 CH572BLEPeri_LIB.h，API 是真实的函数符号，
 *                    由 libCH572BLE.a 提供实现；
 *      - ROM 方式  ：包含 CH572BLE_ROM.h，API 被定义成对固定绝对地址的
 *                    间接调用，因此**不需要链接任何 BLE 库**。
 *--------------------------------------------------------------------------*/
#ifdef CH572BLE_ROM
#include "CH572BLE_ROM.h"
#else
#include "ch572_ble.h"
#endif

/*----------------------------------------------------------------------------
 * 3. 引入 CH572 标准外设驱动头文件（寄存器定义 + 外设 API）
 *--------------------------------------------------------------------------*/
#include "CH57x_common.h"

/*----------------------------------------------------------------------------
 * 4. 引入 HAL 子模块
 *--------------------------------------------------------------------------*/
#include "HAL.h"

#endif /* __CONFIG_H */
