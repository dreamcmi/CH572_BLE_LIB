# -*- coding: utf-8 -*-
"""gen_rf_ram_info.py —— 从链接好的 RF 镜像 ELF 读出它占用的 RAM 区，生成应用侧信息。

为什么需要：
    镜像里有必须在 RAM 执行的代码（.highcode）和变量（.data/.bss），
    但镜像**没有上电入口**，没人替它搬运/清零。
    应用必须：预留这段 RAM（改链接脚本 ORIGIN）、搬 .highcode/.data、清 .bss。

    地址直接从链接好的 ELF 里读，保证永远与镜像真实布局一致，
    不像手工维护的宏那样会漂移。

用法：
    python tools\\gen_rf_ram_info.py <rom.elf> <out.h> <out.ld> --app-flash-end 0x10000
"""
import argparse
import io
import os
import re
import subprocess
import sys

sys.stdout.reconfigure(encoding='utf-8')

BIN = (r'D:\MounRiver\MounRiver_Studio2\resources\app\resources\win32'
       r'\components\WCH\Toolchain\RISC-V Embedded GCC12\bin')
NM = os.path.join(BIN, 'riscv-wch-elf-nm.exe')

NEED = [
    '_rom_rf_highcode_vma_start', '_rom_rf_highcode_vma_end', '_rom_rf_highcode_lma',
    '_data_vma', '_data_lma', '_edata',
    '_sbss', '_ebss',
]


def read_syms(elf):
    out = subprocess.run([NM, '--defined-only', '--numeric-sort', elf],
                         capture_output=True, text=True, errors='replace').stdout
    syms = {}
    for line in out.split('\n'):
        m = re.match(r'^([0-9a-fA-F]{8})\s+(\S)\s+(\S+)$', line.strip())
        if m:
            syms.setdefault(m.group(3), int(m.group(1), 16))
    return syms


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('elf')
    ap.add_argument('out_h')
    ap.add_argument('out_ld')
    ap.add_argument('--app-flash-end', default='0x10000')
    args = ap.parse_args()

    app_end = int(args.app_flash_end, 16)
    syms = read_syms(args.elf)

    miss = [n for n in NEED if n not in syms]
    if miss:
        sys.stderr.write('错误：ELF 里缺少这些符号 —— %s\n' % ', '.join(miss))
        sys.stderr.write('它们由 rom_rf/rom_rf_link.ld 导出，请确认镜像是用那个脚本链的。\n')
        return 2

    hc_vma = syms['_rom_rf_highcode_vma_start']
    hc_size = syms['_rom_rf_highcode_vma_end'] - hc_vma
    hc_lma = syms['_rom_rf_highcode_lma']
    d_vma = syms['_data_vma']
    d_size = syms['_edata'] - d_vma
    d_lma = syms['_data_lma']
    b_vma = syms['_sbss']
    b_size = syms['_ebss'] - b_vma
    reserve_start = 0x20000000
    reserve_end = syms['_ebss']

    if reserve_start != hc_vma:
        sys.stderr.write('警告：.highcode VMA (0x%08X) 不等于 RAM 起点 —— '
                         '镜像可能没从 0x20000000 开始排\n' % hc_vma)
    if reserve_end > 0x20003000:
        sys.stderr.write('错误：镜像占用的 RAM 超出 CH572 的 12 KB\n')
        return 2
    for nm, lma, size in (('.highcode', hc_lma, hc_size), ('.data', d_lma, d_size)):
        if not (app_end <= lma <= lma + size <= 0x3C000):
            sys.stderr.write('错误：%s 的 LMA 0x%08X 不在镜像区间 [0x%05X, 0x3C000)\n'
                             % (nm, lma, app_end))
            return 2

    h = []
    h.append('/* Generated by tools/gen_rf_ram_info.py. Do not edit. */')
    h.append('#ifndef CH572_RF_ROM_RAM_INFO_H')
    h.append('#define CH572_RF_ROM_RAM_INFO_H')
    for k, v in (('RF_ROM_HIGHCODE_VMA', hc_vma), ('RF_ROM_HIGHCODE_SIZE', hc_size),
                 ('RF_ROM_HIGHCODE_LMA', hc_lma), ('RF_ROM_DATA_VMA', d_vma),
                 ('RF_ROM_DATA_SIZE', d_size), ('RF_ROM_DATA_LMA', d_lma),
                 ('RF_ROM_BSS_VMA', b_vma), ('RF_ROM_BSS_SIZE', b_size),
                 ('RF_ROM_RESERVE_START', reserve_start), ('RF_ROM_RESERVE_END', reserve_end),
                 ('RF_ROM_RESERVE_SIZE', reserve_end - reserve_start)):
        h.append('#define %-24s 0x%08Xu' % (k, v))
    h.append('#endif')
    os.makedirs(os.path.dirname(os.path.abspath(args.out_h)), exist_ok=True)
    io.open(args.out_h, 'w', encoding='utf-8').write('\n'.join(h) + '\n')

    ld = ['/* Generated by tools/gen_rf_ram_info.py. Do not edit. */',
          'RF_ROM_RAM_RESERVE_END = 0x%08X;' % reserve_end,
          'RF_ROM_APP_FLASH_END   = 0x%08X;' % app_end,
          '']
    io.open(args.out_ld, 'w', encoding='utf-8').write('\n'.join(ld))

    print('RAM 预留 0x%08X..0x%08X（%d 字节）' % (reserve_start, reserve_end,
                                                reserve_end - reserve_start))
    print('  .highcode %5d B  LMA 0x%08X' % (hc_size, hc_lma))
    print('  .data     %5d B  LMA 0x%08X' % (d_size, d_lma))
    print('  .bss      %5d B' % b_size)
    return 0


if __name__ == '__main__':
    sys.exit(main())
