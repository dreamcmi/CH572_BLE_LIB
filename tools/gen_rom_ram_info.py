"""Generate exact ROM RAM copy ranges from ELF segments; fail on missing metadata."""
import argparse
from pathlib import Path
from elf_image import ElfImage


def generate(elf_path, dst, app_flash_end, snv_size=4096):
    elf = ElfImage(elf_path)
    info = {}
    for name, key in (('.highcode', 'HIGHCODE'), ('.data', 'DATA'), ('.bss', 'BSS')):
        section = elf.sections[name]
        info['ROM_RAM_' + key + '_VMA'] = section['vma']
        info['ROM_RAM_' + key + '_SIZE'] = section['size']
        info['ROM_RAM_' + key + '_END'] = section['vma'] + section['size']
        if name != '.bss':
            info['ROM_RAM_' + key + '_LMA'] = elf.lma(name)
    info['ROM_RAM_BSS_START'] = info['ROM_RAM_BSS_VMA']
    info['ROM_RAM_RESERVE_START'] = min(info['ROM_RAM_HIGHCODE_VMA'], info['ROM_RAM_DATA_VMA'])
    info['ROM_RAM_RESERVE_END'] = info['ROM_RAM_BSS_END']
    info['ROM_RAM_RESERVE_SIZE'] = info['ROM_RAM_RESERVE_END'] - info['ROM_RAM_RESERVE_START']
    if info['ROM_RAM_RESERVE_START'] != 0x20000000 or info['ROM_RAM_RESERVE_END'] > 0x20003000:
        raise ValueError('ROM RAM range is outside CH572 SRAM')
    for key in ('HIGHCODE', 'DATA'):
        lma = info['ROM_RAM_' + key + '_LMA']
        size = info['ROM_RAM_' + key + '_SIZE']
        if not elf.symbols['ROM_BASE'] <= lma <= lma + size <= 0x3C000:
            raise ValueError(f'{key}: invalid Flash load address')
    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    header = ['/* Generated by gen_rom_ram_info.py. Do not edit. */',
              '#ifndef CH572_ROM_RAM_INFO_H', '#define CH572_ROM_RAM_INFO_H']
    header += [f'#define {key:<28} 0x{value:08X}u' for key, value in info.items()]
    header += ['#endif', '']
    dst.write_text('\n'.join(header), encoding='utf-8')
    ld = ['/* Generated. Used by the application linker. */']
    for key in ('ROM_RAM_RESERVE_START', 'ROM_RAM_RESERVE_END'):
        ld.append(f'{key} = 0x{info[key]:08X};')
    ld += [f'ROM_APP_FLASH_END = 0x{app_flash_end:08X};',
           f'SNV_ADDR = 0x{app_flash_end:08X};', f'SNV_SIZE = 0x{snv_size:X};', '']
    dst.with_suffix('.ld').write_text('\n'.join(ld), encoding='utf-8')
    print(f'ROM RAM: {info["ROM_RAM_RESERVE_SIZE"]} bytes, '
          f'0x{info["ROM_RAM_RESERVE_START"]:08X}..0x{info["ROM_RAM_RESERVE_END"]:08X}')
    print(f'Generated {dst} and {dst.with_suffix(".ld")}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('elf')
    parser.add_argument('header')
    parser.add_argument('--app-flash-end', type=lambda s: int(s, 0), default=0x1F000)
    parser.add_argument('--snv-size', type=lambda s: int(s, 0), default=4096)
    args = parser.parse_args()
    generate(args.elf, args.header, args.app_flash_end, args.snv_size)
